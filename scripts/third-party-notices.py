#!/usr/bin/env python3
"""Generate notices from linked Go modules and installed production npm packages."""

import argparse
import json
import os
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD_PARTY_NOTICES.md"


def license_files(directory):
    return sorted(p for p in directory.iterdir() if p.is_file() and
                  re.match(r"^(license|licence|copying|notice)(?:[._-]|$)", p.name, re.I))


def generate():
    dependencies = {}
    for platform in ("linux/amd64", "linux/arm64", "darwin/amd64", "darwin/arm64", "windows/amd64"):
        system, arch = platform.split("/")
        environment = dict(os.environ, GOOS=system, GOARCH=arch, CGO_ENABLED="0")
        rows = subprocess.check_output([
            "go", "list", "-deps", "-f",
            "{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}",
            "./cmd/kist",
        ], cwd=ROOT, env=environment, text=True)
        for row in rows.splitlines():
            if not row.strip():
                continue
            name, version, directory = row.split("\t")
            dependencies[("Go", name, version)] = Path(directory)
    lock = json.loads((ROOT / "web/package-lock.json").read_text(encoding="utf-8"))
    for relative, package in lock["packages"].items():
        if not relative or package.get("dev"):
            continue
        directory = ROOT / "web" / relative
        metadata = json.loads((directory / "package.json").read_text(encoding="utf-8"))
        if metadata["version"] != package["version"]:
            raise SystemExit(f"Installed version does not match lockfile: {relative}; run npm ci")
        dependencies[("npm", metadata["name"], metadata["version"])] = directory
    parts = ["""# Third-party notices

Generated by `python3 scripts/third-party-notices.py` from the Go modules linked
on supported release platforms and the production npm dependency lockfile.
Regenerate after dependency updates; `make check` detects stale notices.
The Go standard library is also covered below. Build/test-only tools are not
part of this inventory. kist's own code is licensed under Apache-2.0; third-party
components retain their respective licenses.

Container images additionally include Debian packages such as FFmpeg, libheif and Poppler.
Their copyright and license notices are retained under `/usr/share/doc/` in the
image. These runtime packages are separate programs, not covered by kist's license.
For the exact installed versions, use `dpkg-query -W` inside the image.
"""]
    goroot = Path(subprocess.check_output(["go", "env", "GOROOT"], cwd=ROOT, text=True).strip())
    go_license = goroot / "LICENSE"
    if not go_license.is_file():
        go_license = goroot.parent / "LICENSE"  # Homebrew keeps notices beside libexec.
    parts.append("\n## Go standard library\n\n```text\n" + go_license.read_text(encoding="utf-8").strip() + "\n```\n")
    for (ecosystem, name, version), directory in sorted(dependencies.items()):
        files = license_files(directory)
        supplement = ROOT / "third_party" / f"{name.replace('/', '__')}-{version}"
        if not files and supplement.is_dir():
            files = license_files(supplement)
        if not files:
            raise SystemExit(f"No license notice found for {ecosystem} {name} {version}")
        parts.append(f"\n## {ecosystem}: {name} {version}\n")
        if supplement.is_dir():
            parts.append("\n" + (supplement / "SOURCE.md").read_text(encoding="utf-8").strip() + "\n")
        for file in files:
            text = file.read_text(encoding="utf-8").strip()
            fence = "`" * max(3, max((len(m[0]) + 1 for m in re.finditer(r"`+", text)), default=3))
            parts.append(f"\n### {file.name}\n\n{fence}text\n{text}\n{fence}\n")
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Third-party notices are stale; run python3 scripts/third-party-notices.py")
        print("Third-party notices match installed dependencies")
    else:
        OUTPUT.write_text(content, encoding="utf-8", newline="\n")
        print(f"Wrote {OUTPUT.name}")


if __name__ == "__main__":
    main()
